let index = 0;
const features = Object.entries(groups).flatMap(([category, items]) => {
  if (items.length !== 16) throw new Error(`${category} must contain 16 distinct capabilities`);
  return items.map((name, i) => ({
    id: `F${String(++index).padStart(3, '0')}`,
    category,
    name,
    status: implemented[category]?.includes(i) ? 'implemented' : 'planned',
    evidence: implemented[category]?.includes(i) ? sourceEvidence[category] : [],
    verification: 'Not yet individually acceptance-tested',
  }));
});
if (new Set(features.map((f) => f.name)).size !== features.length)
  throw new Error('Duplicate feature names');
const inventory = {
  version: 1,
  target: '300+ working, verified related features',
  note: 'Implementation status is source-backed, not a completion claim. Live Google checks and individual acceptance checks remain required.',
  features,
};
